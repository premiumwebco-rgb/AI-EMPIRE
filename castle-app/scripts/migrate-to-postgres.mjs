// One-time migration: data/empire.db (SQLite) -> Supabase Postgres.
// Extends the exact pattern already used by scripts/phase1-import.mjs —
// same principle: move real rows, invent nothing.
//
// Run from castle-app/, after `npm install` and after db/schema.postgres.sql
// has been applied to your Supabase project:
//
//   node --env-file=.env.local scripts/migrate-to-postgres.mjs --dry-run
//   node --env-file=.env.local scripts/migrate-to-postgres.mjs
//
// Requires NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (see
// .env.local.example).
//
// Real-vs-synthetic: data/empire.db also contains the Phase 2 / Phase 2
// gap-fix runtime validation chains (task ids rv-00..rv-06, rv2-00..rv2-08,
// and every activity_feed/notification row generated by them). Those exist
// to prove the task lifecycle scripts work, not as real business history —
// every one of them self-labels "SYNTHETIC" in its own report_outcome. The
// allowlists below are the exact, manually-verified real-record set;
// nothing outside them is ever written to Supabase.
//
// Idempotency:
//   - tasks.id is a plain TEXT PRIMARY KEY -> upserted by id (onConflict).
//   - activity_feed.id / notifications.id are GENERATED ALWAYS AS IDENTITY
//     in db/schema.postgres.sql -> Postgres rejects explicit values on
//     those columns, so the original SQLite integer ids cannot be carried
//     over. Idempotency instead checks each real row's exact (date, text)
//     against what's already in Supabase and skips it if already present,
//     so this script is safe to re-run.
//   - reports are matched by (type, date).

import { DatabaseSync } from "node:sqlite";
import { createClient } from "@supabase/supabase-js";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SQLITE_PATH = join(__dirname, "..", "..", "data", "empire.db");
const DRY_RUN = process.argv.includes("--dry-run");

const REAL_TASK_IDS = ["cq-001", "cq-002", "cq-003"];
const REAL_ACTIVITY_IDS = [1, 2, 3, 4, 5, 6];
const REAL_NOTIFICATION_IDS = [1, 2, 3, 4, 5];

if (!process.env.NEXT_PUBLIC_SUPABASE_URL || !process.env.SUPABASE_SERVICE_ROLE_KEY) {
  console.error("Missing env vars. Run with: node --env-file=.env.local scripts/migrate-to-postgres.mjs");
  process.exit(1);
}

const sqlite = new DatabaseSync(SQLITE_PATH, { readOnly: true });
const supabase = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });

console.log(DRY_RUN ? "=== DRY RUN — nothing will be written ===\n" : "=== LIVE MIGRATION ===\n");

// ---------- tasks ----------
const allTasks = sqlite.prepare("SELECT * FROM tasks").all();
const realTasks = allTasks.filter(t => REAL_TASK_IDS.includes(t.id));
const skippedTasks = allTasks.filter(t => !REAL_TASK_IDS.includes(t.id));

console.log(`tasks: ${allTasks.length} in SQLite -> ${realTasks.length} real (migrate), ${skippedTasks.length} synthetic (skip)`);
for (const t of realTasks) console.log(`  MIGRATE  ${t.id}  [${t.status}]  ${t.raw_command}`);
for (const t of skippedTasks) console.log(`  SKIP     ${t.id}  (synthetic — not in allowlist)`);

let taskCount = 0;
if (!DRY_RUN) {
  for (const t of realTasks) {
    const { error } = await supabase.from("tasks").upsert({
      id: t.id, raw_command: t.raw_command, agent: t.agent, task_type: t.task_type || null,
      status: t.status, queued_at: t.queued_at, started_at: t.started_at, completed_at: t.completed_at,
      dependencies: JSON.parse(t.dependencies || "[]"),
      files_affected: JSON.parse(t.files_affected || "[]"),
      report_input_data: t.report_input_data || null,
      report_actions_taken: t.report_actions_taken || null,
      report_outcome: t.report_outcome, report_reasoning: t.report_reasoning,
      report_files_created: JSON.parse(t.report_files_created || "[]"),
      report_files_modified: JSON.parse(t.report_files_modified || "[]"),
      report_recommendations: t.report_recommendations, report_confidence: t.report_confidence,
      report_next_action: t.report_next_action, report_risks: t.report_risks || null
    }, { onConflict: "id" });
    if (error) { console.error(`  ERROR upserting task ${t.id}:`, error.message); } else { taskCount++; }
  }
}

// ---------- activity_feed (idempotent via exact date+text match) ----------
const allFeed = sqlite.prepare("SELECT * FROM activity_feed ORDER BY id").all();
const realFeed = allFeed.filter(f => REAL_ACTIVITY_IDS.includes(f.id));
const skippedFeed = allFeed.filter(f => !REAL_ACTIVITY_IDS.includes(f.id));

console.log(`\nactivity_feed: ${allFeed.length} in SQLite -> ${realFeed.length} real (migrate), ${skippedFeed.length} synthetic (skip)`);
for (const f of realFeed) console.log(`  MIGRATE  sqlite id=${f.id}  ${f.date}  ${f.agent}: ${f.text.slice(0, 70)}${f.text.length > 70 ? "..." : ""}`);

let feedInserted = 0, feedSkippedDup = 0;
for (const f of realFeed) {
  const { data: existing, error: checkErr } = await supabase
    .from("activity_feed").select("id").eq("date", f.date).eq("text", f.text).limit(1);
  if (checkErr) { console.error(`  ERROR checking activity_feed sqlite id=${f.id}:`, checkErr.message); continue; }
  if (existing && existing.length > 0) {
    feedSkippedDup++;
    console.log(`  ALREADY PRESENT  sqlite id=${f.id} -> Supabase id=${existing[0].id} (skipped, idempotent)`);
    continue;
  }
  if (!DRY_RUN) {
    const { error } = await supabase.from("activity_feed").insert({
      date: f.date, agent: f.agent, business_id: f.business_id, priority: f.priority,
      text: f.text, source: f.source, task_id: f.task_id
    });
    if (error) { console.error(`  ERROR inserting activity_feed sqlite id=${f.id}:`, error.message); continue; }
  }
  feedInserted++;
}

// ---------- notifications (idempotent via exact date+text match) ----------
const allNotifs = sqlite.prepare("SELECT * FROM notifications ORDER BY id").all();
const realNotifs = allNotifs.filter(n => REAL_NOTIFICATION_IDS.includes(n.id));
const skippedNotifs = allNotifs.filter(n => !REAL_NOTIFICATION_IDS.includes(n.id));

console.log(`\nnotifications: ${allNotifs.length} in SQLite -> ${realNotifs.length} real (migrate), ${skippedNotifs.length} synthetic (skip)`);
for (const n of realNotifs) console.log(`  MIGRATE  sqlite id=${n.id}  ${n.date}  [${n.level}] ${n.text.slice(0, 70)}${n.text.length > 70 ? "..." : ""}`);

let notifInserted = 0, notifSkippedDup = 0;
for (const n of realNotifs) {
  const { data: existing, error: checkErr } = await supabase
    .from("notifications").select("id").eq("date", n.date).eq("text", n.text).limit(1);
  if (checkErr) { console.error(`  ERROR checking notification sqlite id=${n.id}:`, checkErr.message); continue; }
  if (existing && existing.length > 0) {
    notifSkippedDup++;
    console.log(`  ALREADY PRESENT  sqlite id=${n.id} -> Supabase id=${existing[0].id} (skipped, idempotent)`);
    continue;
  }
  if (!DRY_RUN) {
    const { error } = await supabase.from("notifications").insert({
      date: n.date, level: n.level, text: n.text, source: n.source, read_at: n.read_at
    });
    if (error) { console.error(`  ERROR inserting notification sqlite id=${n.id}:`, error.message); continue; }
  }
  notifInserted++;
}

